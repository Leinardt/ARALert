-- ============================================================================
-- ARALert - Supabase setup script for the unmanaged api_* tables
-- ----------------------------------------------------------------------------
-- WHY: These 5 models use `managed = False` in apps/academics/models.py, so
--      `python manage.py migrate` does NOT create them on a fresh database.
--
-- WHEN TO RUN: AFTER `python manage.py migrate` has finished against Supabase
--              (the `users` table must already exist for the foreign keys).
--
-- WHERE: Supabase Dashboard -> SQL Editor -> New query -> paste -> Run.
--
-- SAFE TO RE-RUN: every statement uses IF NOT EXISTS.
-- Column names/types mirror the Django model definitions exactly.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. api_aral_activity  (ApiAralActivity)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS api_aral_activity (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      uuid         NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    tutor_id        uuid         NULL     REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    title           varchar(255) NOT NULL,
    description     text         NULL,
    status          varchar(20)  NOT NULL DEFAULT 'pending',
    date_assigned   date         NOT NULL,
    date_completed  date         NULL,
    remarks         text         NULL
);
CREATE INDEX IF NOT EXISTS api_aral_activity_student_id_idx ON api_aral_activity (student_id);
CREATE INDEX IF NOT EXISTS api_aral_activity_tutor_id_idx   ON api_aral_activity (tutor_id);

-- ---------------------------------------------------------------------------
-- 2. api_grade  (ApiGrade)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS api_grade (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      uuid          NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    tutor_id        uuid          NULL     REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    subject         varchar(100)  NOT NULL,
    quarter         integer       NOT NULL,
    score           numeric(5, 2) NOT NULL,
    total_score     numeric(5, 2) NOT NULL,
    component_type  varchar(20)   NOT NULL,
    remarks         text          NULL,
    date_logged     date          NOT NULL,
    batch_id        varchar(50)   NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS api_grade_student_id_idx  ON api_grade (student_id);
CREATE INDEX IF NOT EXISTS api_grade_tutor_id_idx    ON api_grade (tutor_id);
CREATE INDEX IF NOT EXISTS api_grade_date_logged_idx ON api_grade (date_logged DESC);

-- ---------------------------------------------------------------------------
-- 3. api_academic_risk  (ApiAcademicRisk)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS api_academic_risk (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id            uuid        NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    risk_level            varchar(10) NOT NULL,
    details               text        NOT NULL,
    date_created          timestamptz NOT NULL,
    resolved              boolean     NOT NULL DEFAULT false,
    student_acknowledged  boolean     NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS api_academic_risk_student_id_idx ON api_academic_risk (student_id);

-- ---------------------------------------------------------------------------
-- 4. api_attendance_session  (ApiAttendanceSession) - QR sessions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS api_attendance_session (
    id                uuid        PRIMARY KEY,
    creator_id        uuid        NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    session_type      varchar(10) NOT NULL,
    action            varchar(20) NULL,
    aral_activity_id  bigint      NULL REFERENCES api_aral_activity (id) DEFERRABLE INITIALLY DEFERRED,
    expires_at        timestamptz NOT NULL,
    is_active         boolean     NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS api_attendance_session_creator_id_idx ON api_attendance_session (creator_id);
CREATE INDEX IF NOT EXISTS api_attendance_session_active_idx     ON api_attendance_session (is_active, expires_at);

-- ---------------------------------------------------------------------------
-- 5. api_attendance  (ApiAttendance) - student scans + staff DTR
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS api_attendance (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           uuid        NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    tutor_id          uuid        NULL     REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    session_id        uuid        NULL     REFERENCES api_attendance_session (id) DEFERRABLE INITIALLY DEFERRED,
    aral_activity_id  bigint      NULL     REFERENCES api_aral_activity (id) DEFERRABLE INITIALLY DEFERRED,
    role              varchar(20) NOT NULL,
    date              date        NOT NULL,
    time_in           time        NULL,
    time_out          time        NULL,
    arrival_am        time        NULL,
    departure_am      time        NULL,
    arrival_pm        time        NULL,
    departure_pm      time        NULL,
    status            varchar(10) NOT NULL,
    CONSTRAINT api_attendance_user_date_uniq UNIQUE (user_id, date)
);
CREATE INDEX IF NOT EXISTS api_attendance_tutor_id_idx   ON api_attendance (tutor_id);
CREATE INDEX IF NOT EXISTS api_attendance_session_id_idx ON api_attendance (session_id);
CREATE INDEX IF NOT EXISTS api_attendance_date_idx       ON api_attendance (date);

COMMIT;

-- ============================================================================
-- OPTIONAL BUT RECOMMENDED: lock down Supabase's auto-generated public REST API
-- ----------------------------------------------------------------------------
-- Supabase exposes every table in the `public` schema through its REST API
-- (using the public "anon" key). ARALert does NOT use that API - Django talks
-- to Postgres directly as the table owner, which bypasses RLS. Enabling RLS
-- with no policies blocks anonymous REST access without affecting Django.
-- Run this AFTER migrate + the script above.
-- ============================================================================
DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.tablename);
    END LOOP;
END $$;

-- Quick check - should list all 5 tables:
SELECT table_name FROM information_schema.tables
WHERE table_schema = 'public' AND table_name LIKE 'api\_%'
ORDER BY table_name;
