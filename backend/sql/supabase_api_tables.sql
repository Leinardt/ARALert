-- ============================================================================
-- ARALert - Supabase setup script for the unmanaged academic record tables
-- ----------------------------------------------------------------------------
-- WHY: These 5 models use `managed = False` in apps/academics/models.py, so
--      `python manage.py migrate` does NOT create them on a fresh database.
--
-- WHEN TO RUN: AFTER `python manage.py migrate` has finished against Supabase
--              (the `users` and `school_years` tables must already exist).
--
-- WHERE: Supabase Dashboard -> SQL Editor -> New query -> paste -> Run.
--
-- SAFE TO RE-RUN: every statement uses IF NOT EXISTS.
-- Column names/types mirror the Django model definitions exactly.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. aral_activities  (ApiAralActivity)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS aral_activities (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      uuid         NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    tutor_id        uuid         NULL     REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    title           varchar(255) NOT NULL,
    description     text         NULL,
    status          varchar(20)  NOT NULL DEFAULT 'pending',
    date_assigned   date         NOT NULL,
    date_completed  date         NULL,
    remarks         text         NULL
);
CREATE INDEX IF NOT EXISTS aral_activities_student_id_idx ON aral_activities (student_id);
CREATE INDEX IF NOT EXISTS aral_activities_tutor_id_idx   ON aral_activities (tutor_id);

-- ---------------------------------------------------------------------------
-- 2. student_grades  (ApiGrade)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS student_grades (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      uuid          NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    tutor_id        uuid          NULL     REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    subject         varchar(100)  NOT NULL,
    quarter         integer       NOT NULL,
    score           numeric(5, 2) NOT NULL,
    total_score     numeric(5, 2) NOT NULL,
    component_type  varchar(20)   NOT NULL,
    remarks         text          NULL,
    date_logged     date          NOT NULL,
    batch_id        varchar(50)   NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS student_grades_student_id_idx  ON student_grades (student_id);
CREATE INDEX IF NOT EXISTS student_grades_tutor_id_idx    ON student_grades (tutor_id);
CREATE INDEX IF NOT EXISTS student_grades_date_logged_idx ON student_grades (date_logged DESC);

-- ---------------------------------------------------------------------------
-- 3. academic_risks  (ApiAcademicRisk)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS academic_risks (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id            uuid        NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    risk_level            varchar(10) NOT NULL,
    details               text        NOT NULL,
    date_created          timestamptz NOT NULL,
    resolved              boolean     NOT NULL DEFAULT false,
    student_acknowledged  boolean     NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS academic_risks_student_id_idx ON academic_risks (student_id);

-- ---------------------------------------------------------------------------
-- 4. attendance_sessions  (ApiAttendanceSession) - QR sessions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS attendance_sessions (
    id                uuid        PRIMARY KEY,
    creator_id        uuid        NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    session_type      varchar(10) NOT NULL,
    action            varchar(20) NULL,
    aral_activity_id  bigint      NULL REFERENCES aral_activities (id) DEFERRABLE INITIALLY DEFERRED,
    expires_at        timestamptz NOT NULL,
    is_active         boolean     NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS attendance_sessions_creator_id_idx ON attendance_sessions (creator_id);
CREATE INDEX IF NOT EXISTS attendance_sessions_active_idx     ON attendance_sessions (is_active, expires_at);

-- ---------------------------------------------------------------------------
-- 5. attendance_records  (ApiAttendance) - student scans + attendance logs
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS attendance_records (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           uuid        NOT NULL REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    tutor_id          uuid        NULL     REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED,
    session_id        uuid        NULL     REFERENCES attendance_sessions (id) DEFERRABLE INITIALLY DEFERRED,
    aral_activity_id  bigint      NULL     REFERENCES aral_activities (id) DEFERRABLE INITIALLY DEFERRED,
    school_year_id    bigint      NULL     REFERENCES school_years (id) ON DELETE SET NULL,
    role              varchar(20) NOT NULL,
    date              date        NOT NULL,
    time_in           time        NULL,
    time_out          time        NULL,
    arrival_am        time        NULL,
    departure_am      time        NULL,
    arrival_pm        time        NULL,
    departure_pm      time        NULL,
    status            varchar(10) NOT NULL,
    CONSTRAINT attendance_records_user_date_uniq UNIQUE (user_id, date)
);
CREATE INDEX IF NOT EXISTS attendance_records_tutor_id_idx   ON attendance_records (tutor_id);
CREATE INDEX IF NOT EXISTS attendance_records_session_id_idx ON attendance_records (session_id);
CREATE INDEX IF NOT EXISTS attendance_records_date_idx       ON attendance_records (date);

COMMIT;

-- ============================================================================
-- OPTIONAL BUT RECOMMENDED: lock down Supabase's auto-generated public REST API
-- ============================================================================
DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', r.tablename);
    END LOOP;
END $$;

-- Quick check - should list all 5 tables:
SELECT table_name FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('aral_activities', 'student_grades', 'academic_risks', 'attendance_sessions', 'attendance_records')
ORDER BY table_name;
